import time
import re
from datetime import datetime, time as datetime_time

from odoo import _, api, fields, models
from odoo.exceptions import UserError


class DiligenceWhatsAppCampaign(models.Model):
    _name = 'diligence.whatsapp.campaign'
    _description = 'Diligence WhatsApp Bulk Campaign'
    _order = 'create_date desc'

    name = fields.Char(required=True)
    audience_segment_id = fields.Many2one(
        'diligence.contact.segment', string='Recipient Group',
        domain=[('active', '=', True)], ondelete='restrict',
        help='Select a contact segment to include everyone in that group automatically.',
    )
    event_id = fields.Many2one(
        'event.event', string='Event Registrants', ondelete='restrict',
        help='Prepare recipients from registered attendees of this event. Cancelled registrations are excluded.',
    )
    survey_id = fields.Many2one('survey.survey', string='Survey')
    survey_url = fields.Char(string='Survey URL', help='Use a public survey URL or a URL generated by your survey flow.')
    message_template = fields.Text(
        required=True,
        default='Halo %(name)s, silakan isi survey Diligence Academy: %(survey_url)s',
        help='Available placeholders: %(name)s and %(survey_url)s. Use Enter for line breaks; runs of 2 or more spaces are also converted to line breaks when sending.',
    )
    partner_ids = fields.Many2many('res.partner', string='Recipients')
    line_ids = fields.One2many('diligence.whatsapp.campaign.line', 'campaign_id', string='Deliveries')
    state = fields.Selection([
        ('draft', 'Draft'),
        ('prepared', 'Prepared'),
        ('done', 'Processed'),
    ], default='draft', required=True, copy=False)
    pending_count = fields.Integer(compute='_compute_counts')
    sent_count = fields.Integer(compute='_compute_counts')
    error_count = fields.Integer(compute='_compute_counts')

    @api.model
    def _format_campaign_message(self, message):
        message = (message or '').replace('\r\n', '\n').replace('\r', '\n')
        # Odoo's text paste can flatten paragraph breaks into repeated spaces.
        message = re.sub(r' {2,}', '\n', message)
        return message.strip()

    @api.depends('line_ids.state')
    def _compute_counts(self):
        for campaign in self:
            campaign.pending_count = len(campaign.line_ids.filtered(lambda line: line.state == 'pending'))
            campaign.sent_count = len(campaign.line_ids.filtered(lambda line: line.state == 'sent'))
            campaign.error_count = len(campaign.line_ids.filtered(lambda line: line.state == 'error'))

    def action_prepare(self):
        for campaign in self:
            if campaign.state != 'draft':
                raise UserError(_('Only a draft campaign can be prepared.'))
            if campaign.event_id and campaign.audience_segment_id:
                raise UserError(_('Choose either an event or a contact group, not both.'))
            if campaign.event_id:
                registrations = self.env['event.registration'].sudo().search([
                    ('event_id', '=', campaign.event_id.id),
                    ('state', '!=', 'cancel'),
                    ('active', '=', True),
                ])
                if '%(survey_url)s' in (campaign.message_template or '') and not campaign.survey_url:
                    raise UserError(_('Set the survey URL before preparing the campaign.'))
                service = self.env['diligence.whatsapp.service'].sudo()
                prepared_count = 0
                for registration in registrations:
                    phone = service.normalize_number(registration.phone or registration.partner_id.phone)
                    if not phone:
                        continue
                    message = service.render_message(
                        campaign.message_template,
                        survey_url=campaign.survey_url or '',
                        name=registration.name or registration.partner_id.name or '',
                    )
                    self.env['diligence.whatsapp.campaign.line'].sudo().create({
                        'campaign_id': campaign.id,
                        'registration_id': registration.id,
                        'partner_id': False,
                        'phone': phone,
                        'message': campaign._format_campaign_message(message),
                    })
                    prepared_count += 1
                if not prepared_count:
                    raise UserError(_('This event has no active registrations with a valid phone number.'))
                campaign.partner_ids = [(5, 0, 0)]
                campaign.state = 'prepared'
                continue
            if campaign.audience_segment_id:
                segment = campaign.audience_segment_id
                recipients = self.env['res.partner'].sudo().search([
                    ('active', '=', True),
                    ('is_company', '=', False),
                    ('phone', '!=', False),
                    ('diligence_contact_segment_ids', 'in', segment.id),
                ])
                # A newly converted customer must not remain in the prospect audience.
                if segment.code == 'student':
                    active_segment = self.env['diligence.contact.segment'].sudo().search([
                        ('code', '=', 'active_student'), ('active', '=', True),
                    ], limit=1)
                    if active_segment:
                        recipients = recipients.filtered(
                            lambda partner: active_segment not in partner.diligence_contact_segment_ids
                        )
                campaign.partner_ids = [(6, 0, recipients.ids)]
            if not campaign.partner_ids:
                raise UserError(_('Select an event, a recipient group, or at least one recipient with a phone number.'))
            if '%(survey_url)s' in (campaign.message_template or '') and not campaign.survey_url:
                raise UserError(_('Set the survey URL before preparing the campaign.'))
            service = self.env['diligence.whatsapp.service'].sudo()
            for partner in campaign.partner_ids.filtered('phone'):
                existing = campaign.line_ids.filtered(lambda line: line.partner_id == partner)
                if existing:
                    continue
                message = service.render_message(
                    campaign.message_template,
                    partner,
                    survey_url=campaign.survey_url or '',
                )
                message = campaign._format_campaign_message(message)
                self.env['diligence.whatsapp.campaign.line'].sudo().create({
                    'campaign_id': campaign.id,
                    'partner_id': partner.id,
                    'phone': service.normalize_number(partner.phone),
                    'message': message,
                })
            campaign.state = 'prepared'
        return True

    def action_reset_draft(self):
        for campaign in self:
            if campaign.sent_count:
                raise UserError(_('A campaign with sent messages cannot be reset. Its delivery history must be preserved.'))
            campaign.line_ids.sudo().unlink()
            campaign.state = 'draft'
        return True

    def action_delete_campaign(self):
        self.unlink()
        return {'type': 'ir.actions.act_window_close'}

    def unlink(self):
        if any(campaign.sent_count for campaign in self):
            raise UserError(_('A campaign with sent messages cannot be deleted, to preserve the delivery history.'))
        return super().unlink()

    @api.model
    def _get_pending_delivery_batch(self, campaign_id, batch_limit):
        """Return only never-attempted deliveries; failures require review."""
        line_model = self.env['diligence.whatsapp.campaign.line'].sudo()
        line_model.invalidate_model(['state'])
        return line_model.search(
            [('campaign_id', '=', campaign_id), ('state', '=', 'pending')],
            order='id asc',
            limit=batch_limit,
        )

    def action_send(self):
        for campaign in self:
            lock_namespace = 20261123
            self.env.cr.execute('SELECT pg_advisory_lock(%s, %s)', (lock_namespace, campaign.id))
            try:
                campaign.invalidate_recordset(['state'])
                if campaign.state == 'draft':
                    campaign.action_prepare()
                    self.env.cr.commit()

                params = self.env['ir.config_parameter'].sudo()
                batch_limit = max(1, int(params.get_param('diligence.whatsapp.campaign_batch_limit', '10')))
                daily_limit = max(1, int(params.get_param('diligence.whatsapp.daily_campaign_limit', '100')))
                delay = max(0, int(params.get_param('diligence.whatsapp.campaign_delay_seconds', '15')))
                today_start = fields.Datetime.to_string(datetime.combine(fields.Date.context_today(self), datetime_time.min))
                line_model = self.env['diligence.whatsapp.campaign.line'].sudo()
                sent_today = line_model.search_count([
                    ('state', '=', 'sent'), ('sent_at', '>=', today_start),
                ])
                remaining_daily = max(0, daily_limit - sent_today)
                lines = self._get_pending_delivery_batch(
                    campaign.id,
                    min(batch_limit, remaining_daily),
                )
                service = self.env['diligence.whatsapp.service'].sudo()

                for index, line in enumerate(lines):
                    # Persist a claim before the external request. If the web
                    # worker/client disconnects, another click cannot pick this
                    # line again. Ambiguous failures stay out of automatic retry.
                    line.write({'state': 'sending', 'error_message': False})
                    self.env.cr.commit()

                    formatted_message = campaign._format_campaign_message(line.message)
                    if formatted_message != line.message:
                        line.message = formatted_message
                    result = service.send_text(line.phone, line.message)
                    sent = result.get('sent')
                    state = 'sent' if sent else 'skipped' if result.get('skipped') else 'error'
                    line.write({
                        'state': state,
                        'error_message': result.get('error') or False,
                        'sent_at': fields.Datetime.now() if sent else False,
                    })
                    self.env.cr.commit()

                    if sent and delay and index < len(lines) - 1:
                        time.sleep(delay)

                pending_left = line_model.search_count([
                    ('campaign_id', '=', campaign.id), ('state', '=', 'pending'),
                ])
                sending_left = line_model.search_count([
                    ('campaign_id', '=', campaign.id), ('state', '=', 'sending'),
                ])
                if not pending_left and not sending_left:
                    campaign.write({'state': 'done'})
                    self.env.cr.commit()
            finally:
                try:
                    self.env.cr.execute('SELECT pg_advisory_unlock(%s, %s)', (lock_namespace, campaign.id))
                except Exception:
                    # If an unexpected database error aborted the transaction,
                    # clear it before releasing the session-level lock.
                    self.env.cr.rollback()
                    self.env.cr.execute('SELECT pg_advisory_unlock(%s, %s)', (lock_namespace, campaign.id))
        return True


class DiligenceWhatsAppCampaignLine(models.Model):
    _name = 'diligence.whatsapp.campaign.line'
    _description = 'Diligence WhatsApp Bulk Delivery'
    _order = 'create_date desc'

    campaign_id = fields.Many2one('diligence.whatsapp.campaign', required=True, ondelete='cascade', index=True)
    partner_id = fields.Many2one('res.partner', ondelete='set null', index=True)
    registration_id = fields.Many2one('event.registration', string='Event Registration', ondelete='set null', index=True)
    recipient_name = fields.Char(compute='_compute_recipient_name', store=True)
    phone = fields.Char()
    message = fields.Text(required=True)
    state = fields.Selection([
        ('pending', 'Pending'),
        ('sending', 'Sending'),
        ('sent', 'Sent'),
        ('skipped', 'Skipped'),
        ('error', 'Error'),
    ], default='pending', required=True, copy=False, index=True)
    sent_at = fields.Datetime(copy=False, readonly=True)
    error_message = fields.Char(copy=False, readonly=True)

    _recipient_uniq = models.Constraint(
        'unique(campaign_id, partner_id)',
        'A recipient can only be added once to a campaign.',
    )
    _registration_uniq = models.Constraint(
        'unique(campaign_id, registration_id)',
        'An event registration can only be added once to a campaign.',
    )

    @api.depends('partner_id.name', 'registration_id.name')
    def _compute_recipient_name(self):
        for line in self:
            line.recipient_name = (
                line.registration_id.name if line.registration_id
                else line.partner_id.name if line.partner_id else False
            )

    def action_send(self):
        raise UserError(_('Send campaign deliveries from the campaign Send Campaign button.'))
